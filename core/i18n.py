def _t(lang: str, key: str) -> str | None:
    if lang == "ary":
        v = ARY.get(key)
        if v is not None:
            return v
        # clés purement visuelles absentes en darija -> français
        if key in ("brand.name",):
            return None
    return FR.get(key)


def t(key: str, **kwargs) -> str:
    """Traduit une clé dans la langue courante (repli automatique sur le français)."""
    lang = st.session_state.get("lang", "fr")
    text = _t(lang, key)
    if text is None:
        text = FR.get(key, key)
    if kwargs:
        try:
            return text.format(**kwargs)
        except (KeyError, IndexError):
            return text
    return text


